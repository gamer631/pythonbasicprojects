# This is a simple Python script that demonstrates the use of loops
# There are 2 types of loops in python, for loop and while loop. This script will demonstrate the use of both types of loops.

# For loop example
print("For loop example:")
for i in range(5): #meaning of for i in range(5): is that it will iterate through the numbers 0 to 4 (5 is not included) and assign each number to the variable i in each iteration.
    print(i)

# While loop example
print("While loop example:")
i = 0
while i < 5:
    print(i)